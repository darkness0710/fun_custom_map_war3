def part_key(name):
    """Mot doan duong dan -> khoa sap xep. Co so dau ten thi sap theo so."""
    m = re.match(r"^(\d+)", name)
    return (0, int(m.group(1)), name.lower()) if m else (1, 0, name.lower())


def rel_name(path):
    """Ten hien thi: duong dan tuong doi trong src, dung dau / cho gon."""
    return os.path.relpath(path, SRC_DIR).replace(os.sep, "/")


def collect_sources():
    """src/**/*.lua, sap theo so dau ten THU MUC roi den so dau ten FILE.

    Thu tu noi file la thu tu nap. Chi ba rang buoc that su:
    1_config phai truoc (no tao bang CFG), 2_state ngay sau (tao S va
    API), va file khoi dong phai cuoi cung. Moi loi goi cheo file khac
    deu qua API luc CHAY, nen phan giua sap kieu gi cung duoc -- xem
    ADR 0002.
    """
    if not os.path.isdir(SRC_DIR):
        die("khong thay thu muc src: " + SRC_DIR)

    found = []
    for dirpath, dirnames, filenames in os.walk(SRC_DIR):
        dirnames.sort()
        for n in filenames:
            if n.lower().endswith(".lua"):
                found.append(os.path.join(dirpath, n))
    if not found:
        die("src rong -- khong co file .lua nao de noi.")

    ordered = sorted(found, key=lambda p: [part_key(s) for s in
                                           rel_name(p).split("/")])

    loose = [rel_name(p) for p in ordered if "/" not in rel_name(p)]
    if loose:
        print("[canh bao] file nam thang trong src, khong trong thu muc con: "
              + ", ".join(loose))
    unnumbered = [rel_name(p) for p in ordered
                  if any(not re.match(r"^\d+", s)
                         for s in rel_name(p).split("/"))]
    if unnumbered:
        print("[canh bao] thieu so dau ten, xep cuoi: " + ", ".join(unnumbered))
    return ordered


def read_text(path):
    with open(path, "rb") as f:
        raw = f.read()
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    return raw.decode("utf-8", errors="replace")


def strip_block(text):
    """Go khoi da chen truoc do. Idempotent."""
    out, n = BLOCK_RE.subn("\n", text)
    if n == 0:
        # BEGIN con, END mat (file bi cat doi) -> cat tu BEGIN toi het.
        out, n = DANGLING_RE.subn("\n", text)
        if n:
            print("[canh bao] khoi cu thieu marker END, da cat tu BEGIN toi cuoi file.")
    return out, n


def build_block(sources, lang=None):
    """Noi cac file nguon thanh mot khoi do...end duy nhat.

    Ca chuoi file nam chung mot khoi nen local o file truoc van nhin thay
    duoc o file sau. Chieu nguoc lai thi khong -- do la ly do cac module
    goi cheo nhau qua bang API trong 1_core/2_state.lua.
    """
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    parts = [
        BEGIN,
        "-- nguon: src/  |  build luc: %s  |  %d file" % (stamp, len(sources)),
        "-- Sua code o src/*.lua roi chay lai build.py. Sua truc tiep o day se mat.",
        "do",
        "",
        "-- Ba ten dung chung cua ca du an. Khai bao o day chu khong trong",
        "-- file nao, de moi file duoc boc trong khoi do...end rieng.",
        "local CFG, S, API",
        "",
        "-- DAU HIEU SONG. Ghi mot file NGAY khi chunk bat dau nap, bang",
        "-- native tho, khong phu thuoc dong code nao cua du an.",
        "--",
        "-- Tach duoc hai kha nang ma tu ngoai khong phan biet noi:",
        "--   khong co file nay          -> code KHONG nam trong map",
        "--   co file nay, khong co vet  -> chunk nap duoc nhung no giua chung",
        "if PreloadGenClear ~= nil then",
        "  PreloadGenClear(); PreloadGenStart()",
        '  Preload("chunk BAT DAU nap -- build %s")' % stamp,
        '  PreloadGenEnd("DarknessBoot.txt")',
        "end",
    ]
    for path in sources:
        name = rel_name(path)
        body = read_text(path).replace("\r\n", "\n").rstrip()
        parts.append("")
        parts.append("--#region %s" % name)
        # Moi file mot khoi rieng.
        #
        # Lua chi cho 200 bien local SONG CUNG LUC trong mot ham, va ca
        # ban build la mot ham. Gop 14 file vao mot khoi la 494 local --
        # map khong bien dich duoc, game bao "too many local variables".
        # Khoi rieng cho moi file thi local cua no duoc giai phong khi
        # het khoi, nen moi file co han muc 200 cua rieng no.
        #
        # Chay duoc la nho ADR 0002: moi loi goi cheo file da di qua bang
        # API tu dau, khong file nao goi thang local cua file khac.
        parts.append("do")
        parts.append(body)
        parts.append("end")
        parts.append("--#endregion %s" % name)
    # Ghi de CFG.LANG SAU moi file nguon. Dat o day chu khong sua
    # 1_config.lua tren dia: build hai ban khac tieng thi cay lam viec
    # khong bi ban, va "git diff" khong nhay len sau moi lan build.
    if lang:
        parts.append("")
        parts.append("-- build.py --lang " + lang)
        parts.append('CFG.LANG = "' + lang + '"')

    # Dau thoi gian build, in ra dong dau khi vao map. Khong co no thi
    # khong phan biet duoc "code sai" voi "dang chay ban cu" -- da can
    # mot lan voi "-nat card".
    parts.append("")
    parts.append('CFG.BUILD = "' + stamp + '"')

    parts.append("")
    parts.append("end")
    parts.append(END)
    return "\n".join(parts) + "\n"


def strip_lua_noise(text):
    """Bo comment va chuoi de dem tu khoa cho dung."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == "-" and text.startswith("--", i):
            m = re.match(r"--\[(=*)\[", text[i:])
            if m:
                close = "]" + m.group(1) + "]"
                j = text.find(close, i)
                i = n if j < 0 else j + len(close)
            else:
                j = text.find("\n", i)
                i = n if j < 0 else j
            continue
        m = re.match(r"\[(=*)\[", text[i:])
        if m:
            close = "]" + m.group(1) + "]"
            j = text.find(close, i)
            i = n if j < 0 else j + len(close)
            continue
        if c == DQUOTE or c == SQUOTE:
            i += 1
            while i < n and text[i] != c:
                i += 2 if text[i] == "\\" else 1
            i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def block_balance_check(text):
    """Kiem tra can bang khoi.

    Khong phai parser Lua day du, nhung bat duoc loi hay gap nhat khi noi
    file: thieu hoac thua mot end.
    """
    body = strip_lua_noise(text)
    depth = 0
    for m in KW_RE.finditer(body):
        kw = m.group(1)
        if kw in ("function", "if", "do", "repeat"):
            depth += 1
        else:
            depth -= 1
            if depth < 0:
                line = body.count("\n", 0, m.start()) + 1
                return False, "thua mot end quanh dong %d cua ket qua" % line
    if depth != 0:
        return False, "thieu %d end -- con khoi chua dong khi het file" % depth
    return True, "can bang khoi ok (khong co luac de kiem sau hon)"


def check_escapes(text):
    """Bat escape khong hop le trong chuoi ngan.

    Day chinh la loi WC3 bao "invalid escape sequence": duong dan model viet
    mot backslash thi \\S, \\N, \\T... deu khong phai escape hop le cua Lua.
    Cach chac an nhat cho duong dan la dung chuoi tho [[...]] -- trong do
    backslash la ky tu thuong, nen ham nay bo qua han.
    """
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "-" and text.startswith("--", i):
            m = re.match(r"--\[(=*)\[", text[i:])
            if m:
                close = "]" + m.group(1) + "]"
                j = text.find(close, i)
                i = n if j < 0 else j + len(close)
            else:
                j = text.find(NEWLN, i)
                i = n if j < 0 else j
            continue
        m = re.match(r"\[(=*)\[", text[i:])
        if m:
            close = "]" + m.group(1) + "]"
            j = text.find(close, i)
            i = n if j < 0 else j + len(close)
            continue
        if c == DQUOTE or c == SQUOTE:
            quote = c
            i += 1
            while i < n and text[i] != quote:
                if text[i] == BSLASH:
                    nxt = text[i + 1] if i + 1 < n else ""
                    if (nxt not in SIMPLE_ESC and not nxt.isdigit()
                            and nxt not in ("x", "u")):
                        line = text.count(NEWLN, 0, i) + 1
                        near = text[max(0, i - 14):i + 10].replace(NEWLN, " ")
                        return False, ("escape khong hop le %s%s o dong %d cua ket qua"
                                       " -- gan: %s" % (BSLASH, nxt, line, near))
                    i += 2
                else:
                    i += 1
            i += 1
            continue
        i += 1
    return True, ""


