def find_wc3(explicit):
    for p in ([explicit] if explicit else []) + WC3_CANDIDATES:
        if p and os.path.isfile(p):
            return p
    return None


def pack_map(map_dir):
    """Dong goi thu muc map thanh .w3x. Tra ve duong dan file."""
    import w3mpq
    out = os.path.join(BAK_DIR, os.path.basename(map_dir))
    os.makedirs(BAK_DIR, exist_ok=True)
    n, size = w3mpq.pack(map_dir, out)
    print("[ok] dong goi: %d file, %s byte" % (n, format(size, ",")))
    print("[ok] FILE MAP : %s" % out)

    # Chep them vao thu muc Maps de hien trong danh sach map cua game.
    maps = os.path.join(os.path.expanduser("~"), "Documents", "Warcraft III",
                        "Maps")
    if os.path.isdir(maps):
        dest = os.path.join(maps, os.path.basename(map_dir))
        try:
            shutil.copyfile(out, dest)
            print("[ok] va chep : %s" % dest)
            print("            (mo Warcraft -> Single Player -> Custom Game)")
        except Exception as e:
            print("[canh bao] khong chep duoc vao Maps: %s" % e)
    return out


def run_map(map_dir, explicit):
    """Dong goi roi chay thang, khong qua World Editor.

    Hai cai bay cua World Editor mat han o day:
      - Ctrl+F9 dong goi ban trong BO NHO no, khong phai ban tren dia
      - moi lan Save no sinh lai war3map.lua, xoa sach code vua chen

    -loadfile chi nhan FILE .w3x, khong nhan thu muc -- da thu va game
    len den menu roi dung do.
    """
    exe = find_wc3(explicit)
    if exe is None:
        print("[loi] khong thay Warcraft III.exe. Dung --wc3 <duong dan> de chi dinh.")
        return 1
    w3x = pack_map(map_dir)
    print("[run] " + exe)
    print("[run] " + w3x)
    subprocess.Popen([exe, "-launch", "-loadfile", w3x])
    return 0


def write_wct(map_dir, block):
    """Chen khoi code vao o "Custom Script" cua World Editor.

    !!! MAC DINH TAT. World Editor KHONG CHIU NOI doan script lon.

    Da thu: chen khoi 183,873 byte vao war3map.wct. Doc lai thay dung
    dinh dang, luaparser xac nhan doan do la Lua hop le. Nhung lan Save
    ke tiep, World Editor ghi ra mot war3map.wct **1.86 GB** -- trong do
    van chi co DUNG MOT khoi code. Tuc chinh World Editor phinh file ra,
    khong phai script nay ghi lap.

    Chua do duoc nguong an toan. Toi khi nao do duoc thi dung --wct.

    Y TUONG thi van dung: World Editor SINH LAI war3map.lua moi lan Save,
    nen chen vao do thi Save nao cung mat. war3map.wct la noi no luu doan
    script tu viet va CHEP vao war3map.lua moi lan sinh -- dat code o day
    thi Save khong xoa ma tai tao. Chi la World Editor khong chiu noi
    kich thuoc.

    Dinh dang (do tu file World Editor tu ghi):

        uint32  phien ban = 0x80000004
        int32   1
        cstring doan custom script      <- chen o day
        int32   so trigger co text rieng = 0

    Tra ve (da ghi chua, ghi chu).
    """
    p = os.path.join(map_dir, "war3map.wct")
    if not os.path.isfile(p):
        return False, "khong thay war3map.wct"

    raw = open(p, "rb").read()
    if len(raw) < 12:
        return False, "war3map.wct qua ngan"

    ver, one = struct.unpack_from("<Ii", raw, 0)
    end = raw.find(bytes(1), 8)
    if end < 0:
        return False, "war3map.wct: khong thay ket chuoi"
    duoi = raw[end + 1:]

    out = struct.pack("<Ii", ver, one) + block.encode("utf-8") + bytes(1) + duoi
    with open(p, "wb") as f:
        f.write(out)
    return True, "war3map.wct -- %d byte" % len(out)


WCT_MAX = 64 * 1024     # war3map.wct that thi chi vai tram byte


def wct_backup():
    """Ban sao luu war3map.wct. Duoi moi la .orig; .goc la duoi CU, van
    doc duoc de ban sao luu tu truoc lan doi ten khong thanh vo dung."""
    for suffix in (".orig", ".goc"):
        q = os.path.join(BAK_DIR, "war3map.wct" + suffix)
        if os.path.isfile(q):
            return q
    return None


def check_wct_size(map_dir):
    """Bao neu war3map.wct phinh to bat thuong.

    World Editor giu doan Custom Script trong bo nho, va mot lan thu chen
    code vao do da lam no ghi ra file 1.4 GB moi lan Save. Mot lan lot
    vao commit la GitHub chan push (gioi han 100 MB).

    Phep kiem nay re, va no bat truoc khi file kip vao git.
    """
    p = os.path.join(map_dir, "war3map.wct")
    if not os.path.isfile(p):
        return
    n = os.path.getsize(p)
    if n <= WCT_MAX:
        return

    print("")
    print("[!] war3map.wct dang %s byte -- binh thuong chi vai tram." % format(n, ","))

    # Tu khoi phuc luon. De file nay nam do la lan commit sau bi GitHub
    # chan (gioi han 100 MB), va da bi chan hai lan roi.
    bak = wct_backup()
    if bak is not None and os.path.getsize(bak) <= WCT_MAX:
        shutil.copyfile(bak, p)
        print("    Da khoi phuc tu %s (%d byte)."
              % (os.path.basename(bak), os.path.getsize(p)))
    print("    World Editor VAN dang giu doan Custom Script trong bo nho:")
    print("    dong World Editor va KHONG Save, hoac xoa sach o Custom Script")
    print("    trong Trigger Editor (bam vao ten map o dau cay).")
    print("")


