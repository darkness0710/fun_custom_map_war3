def brace_balance_check(text):
    """Kiem tra can bang ngoac nhon.

    Mot bang mo ra ma khong dong lai thi bo dem do/if/function/end van
    bao "can bang" -- da de lot mot lan that: mot dong
    CFG.X = { bi chen nham vao giua khoi comment, va game bao
    "'}' expected (to close '{' at line N)".
    """
    body = strip_lua_noise(text)
    depth = 0
    opened_at = []
    for i, ch in enumerate(body):
        if ch == "{":
            depth += 1
            opened_at.append(body.count(NEWLN, 0, i) + 1)
        elif ch == "}":
            depth -= 1
            if opened_at:
                opened_at.pop()
            if depth < 0:
                line = body.count(NEWLN, 0, i) + 1
                return False, "thua mot } o dong %d cua ket qua" % line
    if depth != 0:
        return False, ("thieu %d } -- bang mo o dong %s cua ket qua chua dong"
                       % (depth, opened_at[0] if opened_at else "?"))
    return True, ""


def check_cross_file_locals(sources):
    """Bat file nay goi thang local function cua file khac.

    Tu khi moi file duoc boc trong khoi do...end rieng (de tranh gioi han
    200 local cua Lua), local cua file A KHONG con nhin thay duoc tu file
    B. Truoc day cung khong nen lam, nhung no tinh co chay duoc; gio thi
    thanh nil luc chay -- va nil chi no khi ai do di trung dong do.

    Moi loi goi cheo file phai di qua bang API. Xem ADR 0002.
    """
    owner, body = {}, {}
    for path in sources:
        t = strip_lua_noise(read_text(path))
        body[path] = t
        for m in re.finditer(r"^\s*local\s+function\s+(\w+)", t, flags=re.M):
            owner.setdefault(m.group(1), set()).add(path)

    out = []
    for name, homes in owner.items():
        pat = re.compile(r"(?<![%.\w])" + re.escape(name) + r"\s*\(")
        for path in sources:
            if path in homes:
                continue
            if pat.search(body[path]):
                out.append("%s goi %s() -- dinh nghia o %s"
                           % (rel_name(path), name,
                              ", ".join(rel_name(h) for h in homes)))
    return out


