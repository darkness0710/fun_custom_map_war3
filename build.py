def find_map(explicit):
    """Tra ve duong dan thu muc map dang folder."""
    if explicit:
        p = explicit if os.path.isabs(explicit) else os.path.join(ROOT, explicit)
        if not os.path.isdir(p):
            die("khong thay thu muc map: " + p)
        return p

    found = [
        os.path.join(ROOT, n)
        for n in sorted(os.listdir(ROOT))
        if n.lower().endswith(MAP_EXTS) and os.path.isdir(os.path.join(ROOT, n))
    ]
    if not found:
        die("khong thay map dang folder (*.w3x / *.w3m) trong " + ROOT)
    if len(found) > 1:
        names = ", ".join(os.path.basename(f) for f in found)
        die("co nhieu map: %s -- dung --map de chi dinh." % names)
    return found[0]


