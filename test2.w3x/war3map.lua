-- Nhung hero chua ai lay.
local function available()
  local out = {}
  for i = 1, #CFG.HEROES do
    local h = CFG.HEROES[i]
    if not (CFG.HERO_UNIQUE and S.heroTaken[h.id]) then
      out[#out + 1] = h
