  local data = BlzGetTriggerSyncData()
  if data == nil then return end

  local slotStr, abilStr = data:match("^(%d+):(%-?%d+)$")
  if slotStr == nil then return end

  applyChoice(pid, tonumber(slotStr), tonumber(abilStr))
end

