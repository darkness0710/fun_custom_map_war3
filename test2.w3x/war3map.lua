local function stripSkillPoints(u)
  if not CFG.STRIP_SKILL_POINTS then return 0, "tat" end
  if UnitModifySkillPoints == nil then return 0, "native khong ton tai" end

  local n = 0
  for _ = 1, 20 do
    if not UnitModifySkillPoints(u, -1) then break end
    n = n + 1
  end
  return n, "ok"
end

