-- 12345 -> "12,345"
local function num(n)
  local s = tostring(math.floor(n))
  local out, neg = "", false
  if s:sub(1, 1) == "-" then neg = true; s = s:sub(2) end
  while #s > 3 do
    out = "," .. s:sub(-3) .. out
    s = s:sub(1, -4)
  end
  out = s .. out
  if neg then out = "-" .. out end
  return out
end

